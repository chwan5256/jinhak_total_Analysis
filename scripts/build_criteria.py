def build():
    out = []
    for r in ROWS:
        tot = sum(e[2] for e in r["elems"] if e[2] is not None)
        known = all(e[2] is not None for e in r["elems"])
        conf = "confirmed" if (known and tot == 100) else "partial"
        # 표준 3역량으로 접기 (앱의 분석 결과와 대조하기 위함)
        std = {AC: 0, CA: 0, CO: 0}
        for _, m, w in r["elems"]:
            if w is not None:
                std[m] += w
        out.append({
            "u": r["u"],
            "tier": TIER_OF.get(r["u"], 0),
            "track": r["track"],
            "stage": r["stage"],                       # 서류100 | 서류+면접
            "elems": [{"name": n, "map": m, "w": w} for n, m, w in r["elems"]],
            "sub": [{"name": n, "w": w} for n, w in r.get("sub", [])],
            "std": std if known else None,             # 표준 3역량 환산 (부분자료면 null)
            "conf": conf,
            "note": r["note"],
            "src": r["src"],
        })
    out.sort(key=lambda x: (x["tier"], x["u"], x["track"]))
    tiers = {}
    for r in out:
        tiers.setdefault(str(r["tier"]), [])
        if r["u"] not in tiers[str(r["tier"])]:
            tiers[str(r["tier"])].append(r["u"])
    doc = {
        "meta": {
            "schema": 1,
            "year": 2027,
            "count": len(out),
            "universities": sorted({r["u"] for r in out}),
            "tierIndex": {str(t): us for t, us in TIERS.items()},
            "tiersWithData": tiers,
            "scope": "학생부종합전형 서류평가만. 논술·교과전형은 다루지 않는다.",
            "note": "각 대학 2027 학생부종합전형 가이드북 또는 수시모집요강에 공시된 서류 평가요소와 반영비율. "
                    "확인하지 못한 비중은 null이며 conf=partial로 표시한다. 추정값은 넣지 않는다.",
            "disclaimer": "최종 확인은 반드시 해당 대학 2027 수시모집요강으로 한다.",
        },
        "rows": out,
    }
    p = pathlib.Path("/home/claude/work/repo/data/criteria.json")
    p.write_text(json.dumps(doc, ensure_ascii=False, indent=1), encoding="utf-8")
    print("criteria.json  %d전형 / %d대학 / %d bytes"
          % (len(out), len(doc["meta"]["universities"]), p.stat().st_size))
    for t in ["1", "2", "3"]:
        print("  tier%s: %s" % (t, ", ".join(tiers.get(t, ["—"]))))
    print("  partial:", [r["u"] + "/" + r["track"] for r in out if r["conf"] == "partial"])

if __name__ == "__main__":
    build()
